#!/usr/bin/env python3
"""Gold/Silver <-> Crystal event flag map for PkMultiplayer's experimental
cross-version story (src/coop/CoopFlagMap.lua).

    tools/gen_flag_map.py <pokegold constants/event_flags.asm> <pokecrystal constants/event_flags.asm> > src/coop/CoopFlagMap.lua

Both files are pret's public disassembly constants (bit order of wEventFlags).
A flag is mapped when the same constant name exists in both games."""
import re, sys

def parse(path):
    idx, out = 0, {}
    for raw in open(path, encoding="utf-8"):
        line = raw.split(";")[0].strip()
        if not line:
            continue
        m = re.match(r"const_def\s*(\d+)?", line)
        if m and line.startswith("const_def"):
            idx = int(m.group(1) or 0)
            continue
        m = re.match(r"const_skip\s*(\d+)?", line)
        if m and line.startswith("const_skip"):
            idx += int(m.group(1) or 1)
            continue
        m = re.match(r"const_next\s+(\d+)", line)
        if m:
            idx = int(m.group(1))
            continue
        m = re.match(r"const\s+(\w+)", line)
        if m:
            out[m.group(1)] = idx
            idx += 1
    return out

gold, crystal = parse(sys.argv[1]), parse(sys.argv[2])
pairs = sorted((g, crystal[n], n) for n, g in gold.items() if n in crystal and not n.startswith("EVENT_TEMPORARY"))
print("-- src/coop/CoopFlagMap.lua -- GENERATED by tools/gen_flag_map.py from pret's")
print("-- pokegold / pokecrystal constants/event_flags.asm: the same event's bit in")
print("-- Gold/Silver and in Crystal (names in both games only).  Data, no engine code.")
print("return {")
print("  -- gold bit -> crystal bit")
print("  g2c = {")
row = []
for g, c, _ in pairs:
    row.append("[%d]=%d" % (g, c))
    if len(row) == 10:
        print("    " + ", ".join(row) + ",")
        row = []
if row:
    print("    " + ", ".join(row) + ",")
print("  },")
print("  count = %d," % len(pairs))
print("}")
sys.stderr.write("gold %d, crystal %d, mapped %d\n" % (len(gold), len(crystal), len(pairs)))
